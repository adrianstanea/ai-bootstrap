#!/usr/bin/env python3
"""Generate marketplace, per-plugin manifests, and agent rule files from their sources.

Usage: tools/build_marketplace.py [--check]

Sources: marketplace-source.json (name, owner), plugins/*/plugin.json (portable manifest) and
optional rules/*.md (frontmatter `paths:` + body).
Outputs: plugins/*/.claude-plugin/plugin.json, .claude-plugin/marketplace.json,
.claude/rules/<name>.md, .github/instructions/<name>.instructions.md.
--check reports drifted files and orphans (exit 1) without writing; write mode deletes
orphans, i.e. generated files whose source was removed (only files carrying the marker).
"""

import json
import os
import re
import sys
from pathlib import Path

# BUILD_MARKETPLACE_ROOT lets tests run against a scratch tree.
ROOT = Path(os.environ.get("BUILD_MARKETPLACE_ROOT") or Path(__file__).resolve().parent.parent)
MARKER = "generated by build_marketplace.py"
KEBAB = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
FRONT = re.compile(r"^---\r?\n(.*?)\r?\n---\r?\n(.*)$", re.DOTALL)


def dump(data) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def skill_name(skill_md: Path) -> str | None:
    m = FRONT.match(skill_md.read_text(encoding="utf-8"))
    if not m:
        return None
    n = re.search(r"^name:\s*(\S+)\s*$", m.group(1), re.MULTILINE)
    return n.group(1).strip("\"'") if n else None


def plugin_outputs(errors: list[str]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    entries = []
    for manifest in sorted((ROOT / "plugins").glob("*/plugin.json")):
        pdir = manifest.parent
        data = json.loads(manifest.read_text(encoding="utf-8"))
        name = data.get("name")
        if name != pdir.name:
            errors.append(f"{manifest}: name {name!r} != directory {pdir.name!r}")
        if not isinstance(name, str) or not KEBAB.match(name):
            errors.append(f"{manifest}: name must be kebab-case")
        for sk in sorted((pdir / "skills").glob("*/SKILL.md")):
            if skill_name(sk) != sk.parent.name:
                errors.append(f"{sk}: name {skill_name(sk)!r} != directory {sk.parent.name!r}")
        out[pdir / ".claude-plugin" / "plugin.json"] = dump(data)
        entries.append(
            {"name": name, "source": f"./plugins/{pdir.name}", "description": data.get("description", "")}
        )
    source = json.loads((ROOT / "marketplace-source.json").read_text(encoding="utf-8"))
    market = {
        **{k: source[k] for k in ("name", "owner", "description") if k in source},
        "plugins": sorted(entries, key=lambda e: e["name"]),
    }
    out[ROOT / ".claude-plugin" / "marketplace.json"] = dump(market)
    return out


def rule_outputs(errors: list[str]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    if not (ROOT / "rules").is_dir():
        return out
    for rule in sorted((ROOT / "rules").glob("*.md")):
        m = FRONT.match(rule.read_text(encoding="utf-8"))
        if not m:
            errors.append(f"{rule}: missing frontmatter")
            continue
        globs = re.findall(r"^\s*-\s*(.+?)\s*$", m.group(1), re.MULTILINE)
        if not globs:
            errors.append(f"{rule}: frontmatter needs a `paths:` list")
            continue
        body = m.group(2).lstrip("\n")
        note = f"<!-- {MARKER}; edit rules/{rule.name} -->\n\n"
        claude = f"---\n{m.group(1)}\n---\n{note}{body}"
        applyto = ",".join(globs)
        copilot = f'---\napplyTo: "{applyto}"\n---\n{note}{body}'
        out[ROOT / ".claude" / "rules" / rule.name] = claude
        out[ROOT / ".github" / "instructions" / f"{rule.stem}.instructions.md"] = copilot
    return out


def find_orphans(outputs: dict[Path, str]) -> list[Path]:
    """Generated files no longer produced by any source. Only marker-carrying rule files and
    plugin manifests of plugins without a source plugin.json qualify."""
    found: list[Path] = []
    for pattern in (".claude/rules/*.md", ".github/instructions/*.instructions.md"):
        for path in sorted(ROOT.glob(pattern)):
            if path not in outputs and MARKER in path.read_text(encoding="utf-8", errors="replace"):
                found.append(path)
    for path in sorted((ROOT / "plugins").glob("*/.claude-plugin/plugin.json")):
        if path not in outputs and not (path.parent.parent / "plugin.json").is_file():
            found.append(path)
    return found


def main() -> int:
    check = "--check" in sys.argv[1:]
    errors: list[str] = []
    outputs = {**plugin_outputs(errors), **rule_outputs(errors)}
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    drift = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        drift.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    orphans = find_orphans(outputs)
    if not check:
        for path in orphans:
            path.unlink()
            print(f"removed orphan: {path.relative_to(ROOT)}")
    elif drift or orphans:
        if drift:
            print("drifted (run tools/build_marketplace.py):", file=sys.stderr)
            for p in drift:
                print(f"  {p}", file=sys.stderr)
        if orphans:
            print("orphans (run tools/build_marketplace.py to delete):", file=sys.stderr)
            for p in orphans:
                print(f"  {p.relative_to(ROOT)}", file=sys.stderr)
        return 1
    print(f"ok: {len(outputs)} files {'up to date' if check else 'written/verified'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
